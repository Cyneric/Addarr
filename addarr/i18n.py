def translate(locale: str, key: str, **values: object) -> str:
    """Format a message in the requested locale, falling back to English for unknown locales.

    Unknown message keys are returned as text. values must supply all named
    format placeholders; missing values raise KeyError.
    """
    index = LOCALES.index(locale) if locale in LOCALES else 0
    template = MESSAGES.get(key)
    return (template[index] if template else key).format(**values)
